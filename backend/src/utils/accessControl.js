const normalizeRole = (role) => ROLE_ALIASES[role] || role;

const getPermissionsForRole = (role) => [
    ...(ROLE_PERMISSIONS[normalizeRole(role)] || []),
];

const hasPermission = (role, permission) =>
    getPermissionsForRole(role).includes(permission);

